#if canImport(SwiftData)
import XCTest
import SwiftData
@testable import FitnessAppData
import FitnessAppCore

/// Phase B (Laufcoaching Dual-Path, Task 5): `isEligibleRestDayForInsertion`/
/// `eligibleRestDaysForInsertion`/`Analysis.insertableRestDays` — die
/// Eignungs-Pruefung fuer "darf ein neuer Cardio-Tag HIER eingefuegt werden",
/// unabhaengig vom bestehenden Ersetzungs-Pfad (`isEligibleForAdjustment`/
/// `cardioAvailability`), siehe `RunCoachPlanAdjustmentTests.swift` fuer
/// diesen.
@available(iOS 17.0, macOS 14.0, *)
@MainActor
final class RunCoachPlanAdjustmentInsertionTests: XCTestCase {

    var container: ModelContainer!
    private var context: ModelContext { container.mainContext }

    override func setUpWithError() throws {
        container = try ModelContainer(for: Schema(AppSchema.types), configurations: ModelConfiguration(isStoredInMemoryOnly: true))
    }

    private func makePlan() -> TrainingPlan {
        let plan = TrainingPlan(name: "Plan", weeks: 8, isActive: true, targetEnvironment: .gym)
        context.insert(plan)
        return plan
    }

    @discardableResult
    private func insert(_ day: TrainingDay, into plan: TrainingPlan) -> TrainingDay {
        context.insert(day)
        plan.days.append(day)
        return day
    }

    // MARK: - isEligibleRestDayForInsertion

    func test_eligibleRestDaysForInsertion_includesAutoGeneratedRestDay() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(name: "Ruhetag", weekday: 2, type: .rest, plan: plan, isAutoFilledPlaceholder: true),
            into: plan
        )
        XCTAssertTrue(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    /// REGRESSION FOR THE REVIEW'S FOUND GAP: a `TrainingDay` built exactly
    /// the way `PlanEditorView.createNewDay(type: .rest)` builds one TODAY —
    /// name: "Ruhetag", no customName, type: .rest, no exercises, no
    /// sessions, AND `isAutoFilledPlaceholder` defaulting to `false` (that
    /// call site is never changed) — must be excluded. The old field-value
    /// coincidence that broke the second review's `name == "Ruhetag"`
    /// heuristic no longer matters, because this predicate no longer looks
    /// at name/customName at all.
    func test_eligibleRestDaysForInsertion_excludesManuallyCreatedRestDay() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(name: "Ruhetag", weekday: 2, type: .rest, plan: plan),
            into: plan
        )
        XCTAssertFalse(day.isAutoFilledPlaceholder)
        XCTAssertFalse(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    /// Unit-level check: a `TrainingDay` constructed WITHOUT passing
    /// `isAutoFilledPlaceholder` explicitly defaults to `false` and is
    /// excluded even though it is, structurally, a genuine old auto-rest-day.
    /// This is the Condition-1 trade-off made explicit as a test, not a
    /// surprise: insertion is unavailable for any plan instantiated before
    /// this change ships, until the plan is recreated.
    ///
    /// This project has no `VersionedSchema`/`SchemaMigrationPlan` anywhere
    /// (confirmed by reading `AppSchema.swift`) — every comparable additive
    /// field (`localizationKey`, `generatorSequenceIndex`, `activatedAt`)
    /// relies exclusively on SwiftData's automatic lightweight migration,
    /// with no dedicated migration test anywhere in this project. This is
    /// a model-default-and-persistence check, matching that established
    /// rigor level — not a bespoke pre-change on-disk-fixture migration test.
    func test_eligibleRestDaysForInsertion_excludesPreMigrationRestDay() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(name: "Ruhetag", weekday: 2, type: .rest, plan: plan, localizationKey: "day.restDay.title"),
            into: plan
        )
        XCTAssertFalse(day.isAutoFilledPlaceholder)
        XCTAssertFalse(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    func test_eligibleRestDaysForInsertion_excludesRestDayWithLoggedSession() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(name: "Ruhetag", weekday: 2, type: .rest, plan: plan, isAutoFilledPlaceholder: true),
            into: plan
        )
        let session = WorkoutSession(startTime: Date(), day: day)
        context.insert(session)
        day.sessions.append(session)
        XCTAssertFalse(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    /// Defensive test: should never actually occur together in practice
    /// (only the rest-day auto-fill path sets `isAutoFilledPlaceholder`),
    /// but the predicate must not rely on that invariant holding elsewhere.
    func test_eligibleRestDaysForInsertion_excludesNonRestDay() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(name: "Legs", weekday: 2, type: .legs, plan: plan, isAutoFilledPlaceholder: true),
            into: plan
        )
        XCTAssertFalse(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    func test_eligibleRestDaysForInsertion_excludesRestDayWithActiveExercises() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(name: "Ruhetag", weekday: 2, type: .rest, plan: plan, isAutoFilledPlaceholder: true),
            into: plan
        )
        let exercise = Exercise(name: "Spontane Uebung", sets: 1, orderIndex: 0, day: day)
        context.insert(exercise)
        day.exercises.append(exercise)
        XCTAssertFalse(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    /// Vierte Review-Runde, Entscheidung 2: `customName` signals the user
    /// engaged with this specific day since generation — excluded despite a
    /// true origin proof.
    func test_eligibleRestDaysForInsertion_excludesManuallyRenamedAutoRestDay() {
        let plan = makePlan()
        let day = insert(
            TrainingDay(
                name: "Ruhetag",
                customName: "Family Day",
                weekday: 2,
                type: .rest,
                plan: plan,
                isAutoFilledPlaceholder: true
            ),
            into: plan
        )
        XCTAssertFalse(RunCoachPlanAdjustment.isEligibleRestDayForInsertion(day))
    }

    // MARK: - analyze: insertableRestDays

    /// "Ganzkoerper 3x"-shaped plan (all strength + isAutoFilledPlaceholder
    /// rest days, no cardio day): expect `cardioAvailability ==
    /// .noEligibleCardioDay` AND `insertableRestDays` non-empty — the two
    /// are independent, not mutually exclusive.
    func test_analyze_reportsInsertableRestDays_forZeroCardioPlan() {
        let plan = makePlan()
        let strengthDay = insert(
            TrainingDay(name: "Ganzkoerper", weekday: 2, type: .fullBody, plan: plan),
            into: plan
        )
        let exercise = Exercise(name: "Squat", sets: 3, orderIndex: 0, day: strengthDay)
        context.insert(exercise)
        strengthDay.exercises.append(exercise)

        let restDay1 = insert(
            TrainingDay(name: "Ruhetag", weekday: 3, type: .rest, plan: plan, isAutoFilledPlaceholder: true),
            into: plan
        )
        let restDay2 = insert(
            TrainingDay(name: "Ruhetag", weekday: 4, type: .rest, plan: plan, isAutoFilledPlaceholder: true),
            into: plan
        )

        let analysis = RunCoachPlanAdjustment.analyze(plan: plan)
        XCTAssertEqual(analysis.cardioAvailability, .noEligibleCardioDay)
        XCTAssertEqual(
            Set(analysis.insertableRestDays),
            Set([restDay1.persistentModelID, restDay2.persistentModelID])
        )
    }
}
#endif
